export const shellDictionaries: Record<Locale, ShellDictionary> = {
  'en-US': shellEnUS,
  'ja-JP': shellJaJP,
  'vi-VN': shellViVN,
};

export function getShellDictionary(locale: Locale): ShellDictionary {
  return shellDictionaries[locale] ?? shellDictionaries[DEFAULT_LOCALE];
}

export function getShellNavLabel(locale: Locale, id: string, fallback: string): string {
  const copy = getShellDictionary(locale);
  return copy.navLabels[id as keyof ShellDictionary['navLabels']] ?? fallback;
}

export function getShellNavBadge(locale: Locale, badge: string): string {
  const copy = getShellDictionary(locale);
  return copy.navBadges[badge as keyof ShellDictionary['navBadges']] ?? badge;
}

